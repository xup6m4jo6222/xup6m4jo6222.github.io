/**
 * 兩層共用的循環相位——第 4 層與第 5 層一起呼吸（2026-08-05 本人拍板）。
 *
 * **同步不需要對時機制。** 兩支繪製程式都用同一個頁面時鐘（`performance.now()`，
 * 時間原點是這一次載入）與同一個週期算相位，就自然同相——這是這一輪原型上最先
 * 被自己否決的想法：一度以為要發明一個「讓兩層對時」的通道，實際上只要**兩邊都不要
 * 各自記一個起點**就好。所以這支不提供任何狀態，只提供一個純函式。
 *
 * 誰改了週期，兩層會一起改——那正是要的：它們不是各自呼吸，是同一次呼吸。
 */

/**
 * 一圈的形狀。0 ＝ 全散，1 ＝ 聚攏（第 5 層排出趨勢的那一刻）。
 *
 * 底是餘弦，所以兩端各停一下、中間走得最快，而**峰值速度算得出解析上界**
 * （行程 × π ÷ 週期），紅線④ 才有一條會報錯的線可以守。
 *
 * `hold` 把曲線往聚攏那一端壓，讓那一刻**停得住**——本人的原話是「過個幾秒又讓它
 * 呈現一個可能有一點點趨勢的感覺」，那句話要成立，趨勢態就不能只是一個掃過去的瞬間。
 * 0 就退回純餘弦。**它只改變停留的分配，不改變峰值**（指數壓縮在 0–1 上是單調的，
 * 最大斜率仍出現在原本那一點且不超過原值），所以紅線④ 的上界不受它影響。
 */
export function cyclePhase(seconds: number, period: number, hold: number): number {
	const raw = (1 - Math.cos((2 * Math.PI * seconds) / period)) / 2;
	return hold <= 0 ? raw : Math.pow(raw, 1 - hold * 0.75);
}

/** 這一刻的相位。**不要傳自己記的起點**——傳頁面時鐘，兩層才會同相（見上）。 */
export const phaseNow = (period: number, hold: number) =>
	cyclePhase(performance.now() / 1000, period, hold);
